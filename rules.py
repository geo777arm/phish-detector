# Функция check_email получает текст письма и возвращает СПИСОК найденных
# признаков. Каждый признак — это пара (объяснение, баллы):
#
#     ("Давят срочностью", 20)
#
# Баллы всех признаков складываются, максимум 100. Чем больше, тем опаснее.
# Пустой список [] значит «подозрительного не нашли».
#
# Сейчас тут одно правило-пример. Твоя задача — добавить остальные.
# Идеи (от простого к сложному):
#   1. Срочность: «срочно», «немедленно», «в течение 24 часов», «urgent»
#   2. Просят секретное: «пароль», «код из смс», «данные карты», «CVV», «password»
#   3. Угрозы: «аккаунт будет заблокирован», «suspended»
#   4. Слишком хорошо, чтобы быть правдой: «вы выиграли», «приз», «бесплатно», «winner»
#   5. Безликое обращение: «Уважаемый клиент», «Dear customer»
#   6. Опасные вложения: .exe, .scr, .zip
#   7. Ссылки на подделки брендов: g00gle, paypa1, sberbank-secure...
#      Подсказка: найти все ссылки в тексте можно так:
#          import re
#          links = re.findall(r"https?://\S+", text)
#   8. Много восклицательных знаков или слов КАПСОМ
#
# Совет: сделай списки слов и проверяй их в цикле, а не пиши 50 if-ов.
# Не забудь text.lower(), чтобы «СРОЧНО» и «срочно» считались одинаково.
#
# Проверить себя: python3 check.py
# ============================================================


def check_email(text):
    signs = []
    lower = text.lower()

    # Правило 1: срочность
    urgent_words = ["срочно", "немедленно", "24 час", "urgent", "immediately", "within 24 hours", "right now", "прямо сейчас"]
    for word in urgent_words:
        if word in lower:
            signs.append(("Давят срочностью", 25))
            break

    #Правило 2: Просят пароль
    asking_password = ["пароль", "код из смс", "password", "code", "otp", "card", "cvv", "номер карты", "данные карты", "код", "очень надо"]
    for word in asking_password:
        if word in lower:
            signs.append(("Просят пароль, код", 75))
            break

    #Правило 3: Угрозы
    intimidation_words = ["suspended", "deleted", "removed", "заблокирован", "отменен", "disabled", "cancelled", "suspended"]
    for word in intimidation_words:
        if word in lower:
            signs.append(("Угрозы", 25))
            break

    #Правило 4: Слишком Хорошо, чтобы быть Правдой
    suspicious_words = ["winner", "won", "prize", "congratulations", "приз", "выйграли", "победитель", "компенсация"]
    for word in suspicious_words:
        if word in lower:
            signs.append(("Слишком хорошо, чтобы быть правдой", 25))
            break

    #Правило 6: Просьба Перейти по Ссылке
    link_words = ["open the file", "open the attachment", "перейдите по ссылке", "file", "файл", "access your account", "войти в ваш аккаунт", "войдите", "log in", "http://"]
    for word in link_words:
        if word in lower:
            signs.append(("Подозрительный файл, ссылка", 50))
            break

    #Правило 7: Повторная Попытка
    retry_wrods = ["was not shipped", "re-delivery", "pay", "не доставлена", "повторная доставка", "оплатите", "не доставлена"]
    for word in retry_wrods:
        if word in lower:
            signs.append(("Повторная попытка", 50))
            break
    

    return signs
